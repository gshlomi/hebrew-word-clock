#!/usr/bin/env python3
"""Shape the finite clock vocabulary with Pillow/libraqm; verify all 1440 layouts.
Run from any directory. Requires Pillow with RAQM and a host C++ compiler.
The generated assets are committed; normal firmware builds do not need Python.
"""
from pathlib import Path
import json
import subprocess
import tempfile
from PIL import Image, ImageDraw, ImageFont, features

ROOT = Path(__file__).resolve().parents[2]
SKETCH = ROOT / 'arduino/hebrew_clock'
assert features.check('raqm'), 'Pillow must include libraqm (HarfBuzz + FriBidi)'
with tempfile.TemporaryDirectory() as temp:
    source = Path(temp) / 'words.cpp'
    source.write_text('''#include <cstdio>
#include <cstring>
#include <cstdint>
#define PROGMEM
#define strncpy_P strncpy
#define pgm_read_ptr(x) (*(x))
#include "time_words.h"
int main() { for(int h=0; h<24; ++h) for(int m=0; m<60; ++m) {
char text[160]; buildTimeString(h,m,text,sizeof(text)); puts(text); } }
''')
    subprocess.run(['c++', '-std=c++17', '-fsanitize=address,undefined', '-I', str(SKETCH), str(source), '-o', temp+'/words'], check=True)
    phrases = subprocess.check_output([temp+'/words'], text=True).splitlines()
assert len(phrases) == 1440
phrases += ['אין חיבור', 'ממתין לשעה']
words = sorted(set(word for phrase in phrases for word in phrase.split()))
font = ImageFont.truetype(str(ROOT/'arduino/fonts/NotoSerifHebrew.ttf'), 64)
# Fixed full-word bitmaps preserve HarfBuzz mark positioning, including nikud.
boxes = {w: font.getbbox(w, direction='rtl') for w in words}
top = min(b[1] for b in boxes.values())
bottom = max(b[3] for b in boxes.values())
height = bottom-top+4
gap, line_gap, max_width = 18, 16, 720
images = {}
for word, (left, _, right, _) in boxes.items():
    im = Image.new('1', (right-left+4, height))
    ImageDraw.Draw(im).text((2-left, 2-top), word, font=font, fill=1, direction='rtl')
    images[word] = im

def layout(phrase):
    lines = [[]]
    width = 0
    for word in phrase.split():
        w = images[word].width
        assert w <= max_width
        if lines[-1] and width + gap + w > max_width:
            lines.append([])
            width = 0
        width += (gap if lines[-1] else 0) + w
        lines[-1].append(word)
    total_h = len(lines)*height + (len(lines)-1)*line_gap
    assert total_h <= 400, (phrase, total_h)
    placements = []
    y = (480-total_h)//2
    for line in lines:
        width = sum(images[w].width for w in line) + gap*(len(line)-1)
        x = (800+width)//2
        for word in line:  # Logical Hebrew order runs from right to left.
            x -= images[word].width
            assert 40 <= x and x+images[word].width <= 760
            placements.append((word, x, y))
            x -= gap
        y += height+line_gap
    return placements, len(lines)

out = ['#pragma once', '// Generated by arduino/tools/generate_words.py; do not edit.',
       '#include <Arduino.h>',
       'struct WordBitmap { const char* text; const uint8_t* bits; uint16_t width; };',
       f'constexpr int WORD_HEIGHT = {height};', f'constexpr int WORD_GAP = {gap};',
       f'constexpr int LINE_GAP = {line_gap};', f'constexpr int TEXT_WIDTH = {max_width};']
for i, word in enumerate(words):
    data = images[word].tobytes()
    out.append(f'const uint8_t word_{i}[] PROGMEM = {{'+','.join(str(b) for b in data)+'};')
out.append('const WordBitmap WORDS[] = {')
for i, word in enumerate(words):
    out.append('{'+json.dumps(word, ensure_ascii=False)+f',word_{i},{images[word].width}'+'},')
out += ['};', 'constexpr size_t WORD_COUNT = sizeof(WORDS)/sizeof(WORDS[0]);']
(SKETCH/'word_bitmaps.h').write_text('\n'.join(out)+'\n')
max_lines = max(layout(p)[1] for p in phrases)
# Representative preview is drawn with the same bitmaps and placement algorithm.
preview = Image.new('RGB', (1600, 1040), 'white')
for n, minute in enumerate([0, 11*60+12, 12*60, 23*60+59]):
    xoff, yoff = (n%2)*800, (n//2)*520
    ImageDraw.Draw(preview).text((xoff+10,yoff+8), f'{minute//60:02}:{minute%60:02}', fill='black')
    for word, x, y in layout(phrases[minute])[0]:
        preview.paste('black', (xoff+x, yoff+30+y), images[word])
preview.save(ROOT/'arduino/layout-preview.png')
print(json.dumps({'minutes_checked':1440, 'unique_words':len(words), 'max_lines':max_lines,
                  'word_height':height, 'bitmap_bytes':sum(len(im.tobytes()) for im in images.values())}))
